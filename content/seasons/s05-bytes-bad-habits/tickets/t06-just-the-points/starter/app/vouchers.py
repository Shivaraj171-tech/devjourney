"""Vouchers for late orders: money off the customer's NEXT order.

Maya's spec (SPEC-41):
  - 45 minutes or less: on time, no voucher (0)
  - 46 to 60 minutes:   a $3.00 voucher (300 cents)
  - more than 60:       a $5.00 voucher (500 cents)

Generated by Byte 🤖 (attempt 3). Not merged until our tests say it's right.
"""

from app.refunds import LATE_AFTER_MINUTES

SMALL_VOUCHER = 300  # cents ($3.00)
BIG_VOUCHER = 500  # cents ($5.00)
VERY_LATE_AFTER_MINUTES = 60


def late_voucher(delivery_minutes):
    """Return the voucher, in cents, for an order that took delivery_minutes to arrive."""
    if delivery_minutes > VERY_LATE_AFTER_MINUTES:
        return BIG_VOUCHER
    if delivery_minutes > LATE_AFTER_MINUTES:
        return SMALL_VOUCHER
    return 0
